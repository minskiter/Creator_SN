"""Initialize/synchronize PostgreSQL without resetting data.

Inspired by SOSDx scripts/init_database.py: inspect, upgrade, then create missing
schema. Unlike generate_schemas(safe=True) alone, this also repairs missing
columns/constraints/indexes on existing tables. Destructive changes are refused.
"""
import argparse
import asyncio
import hashlib
import json
from pathlib import Path
import re
import sys
import uuid

import asyncpg
from tortoise import Tortoise
from tortoise.utils import get_schema_sql

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from api.models.database import build_db_url, tortoise_config

MIGRATIONS = Path(__file__).resolve().parents[1] / 'migrations'
LOCK_ID = 0x43524541544F52


def quote(value):
    return '"' + value.replace('"', '""') + '"'


def normalized(value, schema):
    if not value:
        return value
    # Strip only identifier qualification, never change SQL string defaults.
    parts = re.split(r"('(?:[^']|'')*')", value)
    for index, part in enumerate(parts):
        if index % 2 == 0:
            parts[index] = part.replace(quote(schema) + '.', '').replace(schema + '.', '')
        elif index + 1 < len(parts) and parts[index + 1].startswith('::regclass'):
            for prefix in ("'" + schema + '.', "'" + quote(schema) + '.'):
                if part.startswith(prefix):
                    parts[index] = "'" + part[len(prefix):]
                    break
    return ''.join(parts)


async def snapshot(connection, schema):
    rows = await connection.fetch('''
        SELECT c.relname AS table_name, a.attname AS column_name,
               format_type(a.atttypid,a.atttypmod) AS type,
               a.attnotnull AS not_null, pg_get_expr(d.adbin,d.adrelid) AS default_value
        FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
        JOIN pg_attribute a ON a.attrelid=c.oid
        LEFT JOIN pg_attrdef d ON d.adrelid=c.oid AND d.adnum=a.attnum
        WHERE n.nspname=$1 AND c.relkind='r' AND a.attnum>0 AND NOT a.attisdropped
        ORDER BY c.relname,a.attnum
    ''', schema)
    tables = {}
    for row in rows:
        table = tables.setdefault(row['table_name'], {'columns': {}, 'constraints': {}, 'indexes': {}})
        table['columns'][row['column_name']] = {
            'type': row['type'], 'not_null': row['not_null'],
            'default': normalized(row['default_value'], schema),
        }
    for row in await connection.fetch('''
        SELECT c.relname AS table_name, k.conname AS name, k.contype AS type,
               pg_get_constraintdef(k.oid) AS definition
        FROM pg_constraint k JOIN pg_class c ON c.oid=k.conrelid
        JOIN pg_namespace n ON n.oid=c.relnamespace WHERE n.nspname=$1 AND k.contype IN ('p','u','f','c','x')
    ''', schema):
        if row['table_name'] in tables:
            tables[row['table_name']]['constraints'][row['name']] = {
                'type': row['type'], 'definition': normalized(row['definition'], schema)}
    for row in await connection.fetch('''
        SELECT t.relname AS table_name, i.relname AS name, pg_get_indexdef(i.oid) AS definition
        FROM pg_index x JOIN pg_class i ON i.oid=x.indexrelid
        JOIN pg_class t ON t.oid=x.indrelid JOIN pg_namespace n ON n.oid=t.relnamespace
        WHERE n.nspname=$1 AND NOT EXISTS (SELECT 1 FROM pg_constraint k WHERE k.conindid=i.oid)
    ''', schema):
        if row['table_name'] in tables:
            tables[row['table_name']]['indexes'][row['name']] = normalized(row['definition'], schema)
    return tables


async def desired_schema(connection, sql):
    # DDL is generated by the same ORM/models as the application. A savepoint
    # rolls back the entire scratch schema, including sequences and indexes.
    schema = '_creatorsn_schema_' + uuid.uuid4().hex
    transaction = connection.transaction()
    await transaction.start()
    try:
        await connection.execute(f'CREATE SCHEMA {quote(schema)}')
        await connection.execute(f'SET LOCAL search_path TO {quote(schema)}')
        await connection.execute(sql)
        return await snapshot(connection, schema)
    finally:
        await transaction.rollback()


async def plan_changes(connection, expected, current):
    before, after, errors = [], [], []
    for table, desired in expected.items():
        if table not in current:
            continue  # ORM SQL creates the full missing table.
        existing = current[table]
        has_rows = None
        for name, column in desired['columns'].items():
            prefix = f'ALTER TABLE {quote(table)}'
            if name not in existing['columns']:
                default = column['default']
                if default and 'nextval(' in default:
                    errors.append(f'{table}.{name}: adding a sequence/identity column requires an explicit migration')
                    continue
                if column['not_null'] and default is None:
                    if has_rows is None:
                        has_rows = await connection.fetchval(f'SELECT EXISTS(SELECT 1 FROM {quote(table)} LIMIT 1)')
                    if has_rows:
                        errors.append(f'{table}.{name}: required column has no database default; backfill with a versioned migration')
                        continue
                sql = f'{prefix} ADD COLUMN {quote(name)} {column["type"]}'
                if default is not None:
                    sql += f' DEFAULT {default}'
                if column['not_null']:
                    sql += ' NOT NULL'
                before.append(sql + ';')
                continue
            old = existing['columns'][name]
            if old['type'] != column['type']:
                errors.append(f'{table}.{name}: type {old["type"]} -> {column["type"]} needs an explicit migration')
            if old['not_null'] != column['not_null']:
                if column['not_null']:
                    errors.append(f'{table}.{name}: tightening NOT NULL needs an explicit migration')
                else:
                    before.append(f'{prefix} ALTER COLUMN {quote(name)} DROP NOT NULL;')
            if old['default'] != column['default']:
                if any(v and 'nextval(' in v for v in (old['default'],column['default'])):
                    errors.append(f'{table}.{name}: changing sequence defaults needs an explicit migration')
                else:
                    change = 'DROP DEFAULT' if column['default'] is None else 'SET DEFAULT ' + column['default']
                    before.append(f'{prefix} ALTER COLUMN {quote(name)} {change};')
        # Never silently discard columns removed/renamed in the model.
        for name in existing['columns'].keys() - desired['columns'].keys():
            errors.append(f'{table}.{name}: extra column; removal/rename needs an explicit migration')
        for name, constraint in desired['constraints'].items():
            if any(c['definition'] == constraint['definition'] for c in existing['constraints'].values()):
                continue
            if name in existing['constraints'] or (constraint['type']=='p' and any(c['type']=='p' for c in existing['constraints'].values())):
                errors.append(f'{table}: changed constraint {name} needs an explicit migration')
            else:
                after.append(f'ALTER TABLE {quote(table)} ADD CONSTRAINT {quote(name)} {constraint["definition"]};')
        for name, definition in desired['indexes'].items():
            if name not in existing['indexes']:
                after.append(definition + ';')
            elif existing['indexes'][name] != definition:
                errors.append(f'{table}: changed index {name} needs an explicit migration')
        wanted = {c['definition'] for c in desired['constraints'].values()}
        for name, constraint in existing['constraints'].items():
            if constraint['definition'] not in wanted:
                errors.append(f'{table}: extra constraint {name}; review in an explicit migration')
    return before, after, errors


async def apply_migrations(connection, check):
    await connection.execute('''CREATE TABLE IF NOT EXISTS creator_schema_migrations (
        version TEXT PRIMARY KEY, checksum TEXT NOT NULL, applied_at TIMESTAMPTZ NOT NULL DEFAULT now())''')
    applied = {r['version']: r['checksum'] for r in await connection.fetch('SELECT version,checksum FROM creator_schema_migrations')}
    pending = []
    files = sorted(MIGRATIONS.glob('[0-9]*.sql'))
    known = {p.name for p in files}
    if applied.keys() - known:
        raise ValueError('Database has migration versions not present in this checkout; refusing an implicit downgrade.')
    for path in files:
        sql = path.read_text(encoding='utf-8')
        digest = hashlib.sha256(sql.encode()).hexdigest()
        if path.name in applied:
            if applied[path.name] != digest:
                raise ValueError(f'Applied migration was modified: {path.name}')
        else:
            pending.append(path.name)
            if not check:
                await connection.execute(sql)
                await connection.execute('INSERT INTO creator_schema_migrations(version,checksum) VALUES($1,$2)',path.name,digest)
    return pending


async def synchronize(*, check=False):
    await Tortoise.init(config=tortoise_config())
    try:
        sql = get_schema_sql(Tortoise.get_connection('default'), safe=True)
    finally:
        await Tortoise.close_connections()
    connection = await asyncpg.connect(build_db_url(), timeout=10)
    transaction = connection.transaction()
    await transaction.start()
    try:
        await connection.execute("SET LOCAL search_path TO public")
        await connection.execute("SET LOCAL lock_timeout TO '10s'")
        # Serializes simultaneous runs; DDL and version tracking share one transaction.
        await connection.execute('SELECT pg_advisory_xact_lock($1)', LOCK_ID)
        expected = await desired_schema(connection, sql)
        pending = await apply_migrations(connection, check)
        current = await snapshot(connection, 'public')
        before, after, errors = await plan_changes(connection, expected, current)
        missing = sorted(expected.keys() - current.keys())
        print(json.dumps({'missing_tables': missing, 'pending_migrations': pending,
                          'changes': before + after, 'requires_explicit_migration': errors}, indent=2))
        if check:
            # Roll back scratch bookkeeping too: --check never changes schema/data.
            await transaction.rollback()
            return not (missing or pending or before or after or errors)
        if errors:
            raise ValueError('Unsafe schema changes detected. Add a reviewed SQL migration under backend/migrations; no changes committed.')
        for statement in before:
            await connection.execute(statement)
        await connection.execute(sql)
        for statement in after:
            # ORM CREATE INDEX IF NOT EXISTS may already have added it.
            if statement.startswith('CREATE '):
                statement = statement.replace(' INDEX ', ' INDEX IF NOT EXISTS ', 1)
            await connection.execute(statement)
        # Verify the resulting structure before committing anything.
        final = await snapshot(connection, 'public')
        more_before, more_after, problems = await plan_changes(connection, expected, final)
        if more_before or more_after or problems or expected.keys() - final.keys():
            raise ValueError('Post-upgrade schema verification failed; transaction rolled back.')
        await transaction.commit()
        print('Creator SN PostgreSQL tables and indexes are ready.')
        return True
    except BaseException:
        await transaction.rollback()
        raise
    finally:
        await connection.close()


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='read-only schema check; exit 1 if updates are needed')
    args = parser.parse_args()
    try:
        ready = asyncio.run(synchronize(check=args.check))
        sys.exit(0 if ready else 1)
    except Exception as exc:
        # No connection URL/passwords in user-facing diagnostics.
        print(f'Database synchronization failed ({type(exc).__name__}). Check configuration, connectivity, and the schema plan above.', file=sys.stderr)
        sys.exit(2)
